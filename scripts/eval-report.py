#!/usr/bin/env python3
"""Render e2e/artifacts/eval/{baseline,current} side by side as a review skeleton.

Emits one section per agent, one row per case, with latency, error state and a compact
view of each output. Judgement lines are left for a human to fill in; the numbers are not.
"""
import json, pathlib, sys, textwrap

ROOT = pathlib.Path(__file__).resolve().parents[1]
EVAL = ROOT / "e2e" / "artifacts" / "eval"
AGENTS = ["goal-refiner", "skill-gap", "profiler-init", "path-scheduler", "knowledge-explorer", "knowledge-drafter",
          "document-integrator", "quiz-generator", "feedback-simulator", "profiler-update", "tutor"]

def load(variant):
    out = {}
    for f in (EVAL / variant).glob("*.json"):
        d = json.loads(f.read_text()); out[(d["case"], d["agent"])] = d
    return out

def compact(agent, d):
    if d is None: return "_missing_"
    if "error" in d: return f"**error** {d['error'][:160]}"
    o = d["output"]
    if agent == "goal-refiner": return o["refined_goal"]
    if agent == "skill-gap":
        gaps = o["skill_gaps"]; return f"{len(gaps)} skills, {sum(g['is_gap'] for g in gaps)} gaps: " + "; ".join(f"{g['name']} {g['current_level']}→{g['required_level']}" for g in gaps)
    if agent.startswith("profiler"):
        c = o["cognitive_status"]; return f"progress {c['overall_progress']}%, mastered {len(c['mastered_skills'])}, in progress {len(c['in_progress_skills'])}; style: {o['learning_preferences']['content_style'][:80]}"
    if agent == "path-scheduler": return f"{len(o['learning_path'])} sessions: " + " → ".join(s["title"] for s in o["learning_path"])
    if agent == "knowledge-explorer": return f"{len(o['knowledge_points'])} points: " + "; ".join(f"{k['name']} ({k['type']})" for k in o["knowledge_points"])
    if agent == "knowledge-drafter": return f"{len(o['content'])} chars, {o['content'].count(chr(10)+'**')} bold headings, {o['content'].count('```')//2} code blocks; title: {o['title']}"
    if agent == "document-integrator": s = o["structure"]; return f"title: {s['title']}; overview {len(s['overview'])} chars; summary {len(s['summary'])} chars; markdown {len(o['markdown'])} chars"
    if agent == "quiz-generator": return f"{len(o['single_choice_questions'])} single, {len(o['true_false_questions'])} true/false; first: {o['single_choice_questions'][0]['question'][:90] if o['single_choice_questions'] else '—'}"
    if agent == "feedback-simulator": return f"progression: {o['feedback']['progression'][:120]}"
    if agent == "tutor": return f"{len(o)} chars: {o[:140].replace(chr(10),' ')}"
    return json.dumps(o)[:160]

def main():
    b, c = load("baseline"), load("current")
    cases = sorted({k[0] for k in list(b) + list(c)})
    lines = ["<!-- generated by scripts/eval-report.py; judgement lines are hand-written -->", "", "# Prompt evaluation", ""]
    lines += [f"Cases: {', '.join(cases)}. Baseline = tag `prompts-baseline`, current = working tree. Same model, same inputs, live calls.", ""]
    for a in AGENTS:
        lines += [f"## {a}", "", "| case | baseline | current |", "|---|---|---|"]
        for cs in cases:
            bd, cd = b.get((cs, a)), c.get((cs, a))
            ms = lambda d: f" `{d['ms']//1000}s`" if d else ""
            lines.append(f"| {cs} | {compact(a, bd)}{ms(bd)} | {compact(a, cd)}{ms(cd)} |")
        lines += ["", "**Judgement:** _to fill: better / same / worse, and why_", ""]
    (ROOT / "e2e" / "artifacts" / "eval" / "report.md").write_text("\n".join(lines))
    print("wrote", ROOT / "e2e" / "artifacts" / "eval" / "report.md")

if __name__ == "__main__":
    main()
